"""JT1: the tower of the frame wave -- where the law stops at second order and where it does not.

The owner's question: the higher orders live in the Jacobian tower; how do curvature and flatness enter?
Sources: RKF Theorem 42 (typed tower L_{n+1} = nabla L_n; termination for polynomial data; generating object
sum t^k/k! nabla^k; tower observers: a higher layer repairs a target the lower layers are blind to), NT-3
(X = G^-1 dG), RMG1 (response element <-> point of the hyperbolic plane; curvature needs the axis to turn;
rigidity [H, dH] = 0), TP1 (law Q), GW1 (second order), GR2-G1 (memory is removed at a point by a frame change).
Transverse frame block M(t, z) (symmetric), response element G = M^T M.
J1  EXACT, all orders:   Q = (1/4)[ tr(X_t^2) - tr(X_z^2) ] - [ (d_t ln det M)^2 - (d_z ln det M)^2 ],  X = G^-1 dG.
    The law of the wave is the invariant square of NT-3's X.
J2  Unit volume, G = Exp(-sigma (cos phi K + sin phi L)):
        Q = (1/2)[ sigma_t^2 - sigma_z^2 + sinh^2(sigma) (phi_t^2 - phi_z^2) ] .
J3  FLAT TOWER.  If the axis does not turn (phi constant; [G, dG] = 0) the law is exactly quadratic in sigma:
    every layer above the second vanishes.  One polarisation never acts on itself.
J4  CURVED TOWER.  If the axis turns, sinh^2 sigma = sigma^2 + sigma^4/3 + ...: the first higher layer is
    (1/6) sigma^4 (phi_t^2 - phi_z^2), and all layers are generated by the one closed form of J2.
J5  Waves travelling one way (functions of t - z) make every layer vanish: Q = 0 exactly.
J6  Tower observer at a point of the static field m = r_s/r + c0 + c1 (r - r0) (c0, c1: what a change of frame can
    add): layers 1 and 2 are blind to r_s; layer 3 recognises it, r_s = m'' r0^3 / 2.
Symbolic algebra with sympy for J1-J5; exact rationals for J6.  Python 3.12.
"""
from fractions import Fraction as F
