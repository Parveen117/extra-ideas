T, X, Y, Z = sp.symbols('T X Y Z', real=True)
COORDS = (T, X, Y, Z)


def law_from_frame(M):
    E = sp.eye(4)
    E[1, 1], E[1, 2], E[2, 1], E[2, 2] = M[0, 0], M[0, 1], M[1, 0], M[1, 1]
    c = tp.structure_in(COORDS, E)
    I1, I2, I3 = tp.invariants(c)
    return sp.simplify(sp.Rational(1, 4)*I1 + sp.Rational(1, 2)*I2 - I3)


def law_from_response(M):
    G = M.T*M
    Gi = G.inv()
    Xt, Xz = Gi*sp.diff(G, T), Gi*sp.diff(G, Z)
    d = M.det()
    vol = (sp.diff(sp.log(d), T))**2 - (sp.diff(sp.log(d), Z))**2
    return sp.simplify(sp.Rational(1, 4)*((Xt*Xt).trace() - (Xz*Xz).trace()) - vol)


def exact_identity():
    rows = []
    for M in (sp.Matrix([[1 + T*Z, T], [T, 2 + Z**2]]),
              sp.Matrix([[2 + T, Z - T], [Z - T, 3 + T*Z]]),
              sp.Matrix([[1 + T**2, 0], [0, 1 + Z]])):
        diff = sp.simplify(law_from_frame(M) - law_from_response(M))
        if diff != 0:
            raise ValueError('the law is not the invariant square of X')
        rows.append(str(M.tolist()))
    return rows


def hyperbolic_form():
    s = sp.Function('sigma')(T, Z)
    f = sp.Function('phi')(T, Z)
    K = sp.Matrix([[1, 0], [0, -1]])
    L = sp.Matrix([[0, 1], [1, 0]])
    n = sp.cos(f)*K + sp.sin(f)*L
    G = sp.cosh(s)*sp.eye(2) - sp.sinh(s)*n            # Exp(-sigma n), unit determinant
    Gi = sp.cosh(s)*sp.eye(2) + sp.sinh(s)*n
    if sp.simplify(G*Gi - sp.eye(2)) != sp.zeros(2, 2):
        raise ValueError('response element inverse failed')
    Xt, Xz = sp.simplify(Gi*sp.diff(G, T)), sp.simplify(Gi*sp.diff(G, Z))
    Q = sp.simplify(sp.Rational(1, 4)*((Xt*Xt).trace() - (Xz*Xz).trace()))
    want = sp.Rational(1, 2)*(sp.diff(s, T)**2 - sp.diff(s, Z)**2 + sp.sinh(s)**2*(sp.diff(f, T)**2 - sp.diff(f, Z)**2))
    if sp.simplify((Q - want).rewrite(sp.exp)) != 0:
        raise ValueError('hyperbolic form failed')
    comm = sp.simplify(G*sp.diff(G, T) - sp.diff(G, T)*G)
    rigid = sp.simplify(comm.subs(sp.diff(f, T), 0))
    if rigid != sp.zeros(2, 2) or sp.simplify(comm) == sp.zeros(2, 2):
        raise ValueError('rigidity: [G, dG] must vanish exactly when the axis does not turn')
    q_rigid = sp.simplify(want.subs({sp.diff(f, T): 0, sp.diff(f, Z): 0}))
    eps = sp.Symbol('epsilon')
    tower = sp.series(sp.sinh(eps)**2, eps, 0, 7).removeO()
    layers = {int(k): str(tower.coeff(eps, k)) for k in (2, 4, 6)}
    if layers != {2: '1', 4: '1/3', 6: '2/45'}:
        raise ValueError('tower coefficients failed')
    u = sp.Function('S')(T - Z)
    v = sp.Function('P')(T - Z)
    one_way = sp.simplify(want.subs({s: u, f: v}).doit())
    if one_way != 0:
        raise ValueError('one-way waves must give zero at every order')
    from sympy.calculus.euler import euler_equations
    eqs = [sp.simplify(e.lhs) for e in euler_equations(want, [s, f], [T, Z])]
    return dict(law=str(want), rigid_law=str(q_rigid), layers=layers, one_way=str(one_way), equations=[str(e) for e in eqs])


def tower_observer():
    """static field near r0: m = r_s/r + c0 + c1 (r - r0).  Layers: value, first and second derivative at r0."""
    r0 = F(5)
    def layers(rs, c0, c1):
        return (rs/r0 + c0, -rs/r0**2 + c1, 2*rs/r0**3)
    blind1 = (F(3), -F(3)/r0, F(0))
    blind2 = (F(3), -F(3)/r0, F(3)/r0**2)
    l1, l2 = layers(*blind1), layers(*blind2)
    if l1[0] != 0 or l2[0] != 0 or l2[1] != 0:
        raise ValueError('blind directions failed')
    if l2[2] == 0:
        raise ValueError('layer three must see the source')
    for rs, c0, c1 in ((F(3), F(1, 7), F(-2, 9)), (F(11, 2), F(0), F(4)), (F(0), F(5), F(1))):
        if layers(rs, c0, c1)[2]*r0**3/2 != rs:
            raise ValueError('decoder at layer three failed')
    return dict(blind_at_layer_1=True, blind_at_layer_2=True, recognised_at_layer=3, decoder="r_s = m'' r0^3 / 2")


def run():
    return dict(observer=tower_observer(), wave=hyperbolic_form(), identity=exact_identity())


